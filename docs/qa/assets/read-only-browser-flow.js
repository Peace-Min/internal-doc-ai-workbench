async (page) => {
  const original = '합성 프로젝트는 다음 주 시작합니다.\n검토 조건은 예산 승인입니다.';
  const check = (value, message) => { if (!value) throw new Error(message); };
  await page.getByRole('textbox', { name: '문서 내용 (직접 변경 가능)' }).fill(original);
  await page.getByRole('button', { name: '선택 개체 읽기' }).click();
  check(await page.locator('#source').textContent() === original, 'multiline source was not preserved');
  await page.getByRole('button', { name: '요약하기', exact: true }).click();
  await page.locator('#answer-section').waitFor();
  check(await page.locator('#demo-text').inputValue() === original, 'summary changed document');
  check(!await page.getByRole('button', { name: '원래 개체에 적용' }).isVisible(), 'summary offers document apply');
  await page.screenshot({ path: 'output/playwright/read-only-summary.png', fullPage: true });
  await page.getByRole('combobox', { name: '작업', exact: true }).selectOption('ask');
  check(await page.locator('#send').isDisabled(), 'mode change retained stale target');
  await page.getByRole('button', { name: '선택 개체 읽기' }).click();
  await page.locator('#instruction').fill('어떤 승인 조건이 필요한가요?');
  const unsafe = '<img src=x onerror=alert(1)>\n<script>alert(1)</script>';
  await page.route('**/api/propose', route => route.fulfill({ json: { operation: 'ask', answer: unsafe, mode: 'openai-compatible' } }));
  await page.getByRole('button', { name: '질문하기', exact: true }).click();
  await page.getByText(unsafe, { exact: true }).waitFor();
  check(await page.locator('#answer img, #answer script').count() === 0, 'answer became HTML');
  check(await page.locator('#demo-text').inputValue() === original, 'question changed document');
  await page.unroute('**/api/propose');
  await page.getByRole('combobox', { name: '작업', exact: true }).selectOption('replace_text');
  await page.getByRole('button', { name: '선택 개체 읽기' }).click();
  check((await page.locator('#status').textContent()).includes('한 문단만 지원'), 'multiline edit was accepted');
  check(await page.locator('#send').isDisabled(), 'invalid edit target enabled send');
  await page.locator('#demo-text').fill('합성 원문입니다.');
  await page.getByRole('button', { name: '선택 개체 읽기' }).click();
  await page.locator('#instruction').fill('간결하게 보완');
  await page.getByRole('button', { name: '수정안 요청' }).click();
  await page.locator('#proposal-section').waitFor();
  await page.locator('#demo-text').fill('사용자가 변경한 원문');
  await page.getByRole('button', { name: '원래 개체에 적용' }).click();
  check((await page.locator('#status').textContent()).includes('원문이 변경'), 'source conflict was not rejected');
  check(await page.locator('#demo-text').inputValue() === '사용자가 변경한 원문', 'conflict overwrote user text');
  await page.getByRole('button', { name: '선택 개체 읽기' }).click();
  await page.getByRole('button', { name: '수정안 요청' }).click();
  await page.locator('#proposal-section').waitFor();
  await page.getByRole('button', { name: '원래 개체에 적용' }).click();
  check(await page.locator('#demo-text').inputValue() === '[모의 수정안] 사용자가 변경한 원문', 'existing edit flow regressed');
  console.log('PASS: multiline summary, read-only question, plain-text HTML display, mode reset, edit restriction, conflict rejection and normal apply');
}
